#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'hitman.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const sw = fs.readFileSync(path.join(root, 'service-worker.js'), 'utf8');
const workflow = fs.readFileSync(path.join(root, '.github/workflows/validate-index.yml'), 'utf8');

assert.match(source, /name: NAME, cost: 2200, hp: 95800, atk: 8900, secondAtk: 5100/);
assert.match(source, /multiAttack: \[8900, 5100\], range: 220, spd: 0\.8, interval: 1/);
assert.match(source, /recharge: 75/);
assert.match(source, /id: 'hitman_tracking'/, '追跡マーカーを独立スキルとして登録');
assert.match(source, /id: 'hitman_ride'/, '騎乗を独立スキルとして登録');
assert.match(source, /id: 'hitman_counter'/, '転移反撃を独立スキルとして登録');
assert.match(source, /function hitmanSkill\(id\)/, '戦闘処理は独立スキルデータを参照');
assert.match(source, /Number\(skill\?\.damageMultiplier \|\| 5\)/, '追跡マーカーの倍率をスキルデータから参照');
assert.match(source, /Number\(skill\.damageMultiplier \|\| 15\)/, '転移反撃の倍率をスキルデータから参照');
assert.match(source, /trait: '黒', rarity: '伝説レア'/);
assert.match(source, /strong: \{ 神話: 5 \}, resist: \{ 神話: 0\.15 \}/);
assert.match(source, /curseImmune: true, stopImmune: true, waveImmune: true/);
assert.match(source, /reflectImmune: true/);
assert.match(source, /safeDamage = Math\.min\(safeDamage, Math\.max\(1, Number\(target\.maxhp \|\| 1\) \* 0\.1\)/);
assert.match(source, /Math\.round\(actual \* 0\.8\)/);
assert.match(source, /Math\\.random\\(\\) >= Number\\(skill\\.chance \\?\\? 0\\.25\\)/);
assert.match(source, /Number\\(unit\\.atk \\|\\| 8900\\) \\* Number\\(skill\\.damageMultiplier \\|\\| 15\\)/);
assert.match(source, /Number\\(dealt \\|\\| 0\\) \\* Number\\(skill\\.healRatio \\?\\? 0\\.5\\)/);
assert.match(source, /hitmanSkill2Uses \|\| 0\) >= 2/);
assert.match(source, /hitmanRideUntil = Number\\(stageTime \\|\\| 0\\) \\+ Number\\(skill\\?\\.duration \\|\\| 3\\)/);
assert.match(source, /unit\\.hitmanNextRideAt \\+= interval/);
assert.match(source, /unit\\.hitmanRiding \\? Number\\(hitmanSkill\\('hitman_ride'\\)\\?\\.speedBonus \\|\\| 2\\)/);
assert.match(source, /target\.festivalRegenDisabledUntil/);
assert.match(source, /const originalEnemyAttackTarget = enemyAttackTarget/);
assert.match(source, /if \(suppressHealing && originalHealOnKill\) e\.ability\.healOnKill = 0/);
assert.match(source, /Number\(money \|\| 0\) \+ 75/);
assert.match(source, /rechargeLeft\[unit\.cardIndex\] \* 0\.97/);
assert.match(source, /unit\.hitmanKillStacks = Math\.min\(20/);
assert.match(source, /const count = Math\\.max\\(1, Math\\.floor\\(Number\\(skill\\?\\.count \\|\\| 3\\)\\)\\)/);
assert.match(source, /document\.getElementById\('world'\)/, '追跡マーカーはマップ本体に配置する');
assert.match(source, /worldElement\.appendChild\(marker\)/, '追跡マーカーはマップ座標系に所属させる');
assert.match(source, /bottom:67px/, '追跡マーカーはユニットと同じレーン高さに表示する');
assert.doesNotMatch(source, /fieldElement\.appendChild\(marker\)/, '画面側のfieldに配置しない');
assert.match(source, /x -= 120 \* dt/);
assert.match(source, /Number\\(skill\\?\\.damageMultiplier \\|\\| 5\\)/);
assert.match(source, /setTimeout\(\(\) => originalFollowup\(source, target, baseAttack, hitIndex\), 100\)/);
assert.match(source, /selectedChapter\) === 7/);
assert.match(source, /selectedStage\) === 48/);
assert.doesNotMatch(source, /gun|firearm|銃|拳銃|ライフル/i, '追跡マーカー演出に武器機構を含めない');

assert.match(html, /GAME_VERSION='v1.9.61'/);
assert.match(html, /ヒットマン木下/);
assert.match(html, /\.\/hitman\.js\?v=20261105-hitman/);
assert.match(sw, /kinoshita-daisen-v75/);
assert.match(sw, /\.\/hitman\.js/);
assert.match(workflow, /node --check hitman\.js/);
assert.match(workflow, /node tests\/hitman-kinoshita\.test\.js/);
process.stdout.write('ヒットマン木下テスト成功：基本性能、特性、固有能力、解放条件、追跡マーカー、キャッシュを確認しました。\n');