#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'hitman.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const sw = fs.readFileSync(path.join(root, 'service-worker.js'), 'utf8');
const workflow = fs.readFileSync(path.join(root, '.github/workflows/validate-index.yml'), 'utf8');

assert.match(source, /name: NAME, cost: 2200, hp: 100000, atk: 8500, secondAtk: 5100/);
assert.match(source, /multiAttack: \[8500, 5100\], range: 220, spd: 0\.8, interval: 0\.8/);
assert.match(source, /recharge: 70/);
assert.match(source, /id: 'hitman_tracking'.*?count: 2, interval: 0\.25, damageMultiplier: 3/s);
assert.match(source, /id: 'hitman_counter'.*?chance: 0\.15, cooldown: 20, maxUses: 1, damageMultiplier: 7, healRatio: 0\.25/s);
assert.match(source, /strong: \{ 神話: 3 \}, resist: \{ 神話: 0\.40 \}/);
assert.match(source, /function hitmanAttackDamage\(unit, hitIndex = 0\)/);
assert.match(source, /const multiplier = Number\(hitIndex\) === 1 \? 5100 \/ 8500 : 1/);
assert.match(source, /function syncHitmanMultiAttack\(unit\)/);
assert.match(source, /unit\.multiAttack = \[firstHit, secondHit\]/);
assert.match(source, /Number\(skill\.chance \?\? 0\.15\)/);
assert.match(source, /Number\(unit\.atk \|\| 8500\) \* Number\(skill\.damageMultiplier \|\| 7\)/);
assert.match(source, /Number\(dealt \|\| 0\) \* Number\(skill\.healRatio \?\? 0\.25\)/);
assert.match(source, /Number\(skill\.maxUses \|\| 1\)/);
assert.match(source, /Number\(skill\?\.count \|\| 2\)/);
assert.match(source, /Math\.round\(actual \* 0\.35\)/);
assert.match(source, /safeDamage = Math\.min\(safeDamage, Math\.max\(1, Number\(target\.maxhp \|\| 1\) \* 0\.1\)/);
assert.match(source, /target\.festivalRegenDisabledUntil/);
assert.match(source, /Number\(money \|\| 0\) \+ 75/);
assert.match(source, /rechargeLeft\[unit\.cardIndex\] \* 0\.97/);
assert.match(source, /unit\.hitmanKillStacks = Math\.min\(20/);
assert.match(source, /document\.getElementById\('world'\)/);
assert.match(source, /worldElement\.appendChild\(marker\)/);
assert.match(source, /bottom:67px/);
assert.doesNotMatch(source, /fieldElement\.appendChild\(marker\)/);

assert.match(html, /GAME_VERSION='v1\.9\.82'/);
assert.match(html, /多段攻撃の詳細（レベル補正後）/);
assert.ok(html.includes("5100*(detailStat('atk')/8500)"), '2段目の表示に新しい基礎攻撃力と補正率を使用');
assert.ok(html.includes("Math.round(5100*(detailStat('atk')/8500))"), '2段目の戦闘整数値を新しい基礎攻撃力に同期');
assert.match(sw, /kinoshita-daisen-v124/);
assert.match(sw, /\.\/hitman\.js/);
assert.match(workflow, /node --check hitman\.js/);
assert.match(workflow, /node tests\/hitman-kinoshita\.test\.js/);
process.stdout.write('ヒットマン木下 v1.9.83 regression checks passed.\n');
