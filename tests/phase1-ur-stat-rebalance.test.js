'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');

const genesis = fs.readFileSync('genesis.js','utf8');
const evil = fs.readFileSync('evil-kinoshita.js','utf8');
const kwl = JSON.parse(fs.readFileSync('supabase/functions/kwl-spectator-battle/character-data.json','utf8'));
assert.match(genesis,/genesisCard\.hp=100000;genesisCard\.atk=30000/);
assert.match(genesis,/genesisCounterCard\.hp=65000;genesisCounterCard\.atk=12000;genesisCounterCard\.range=900;genesisCounterCard\.interval=3\.8/);
assert.match(evil,/name: ALLY_NAME,[\s\S]{0,160}hp: 500000,[\s\S]{0,60}atk: ALLY_FORMS\.robot\.atk/);
const byName=Object.fromEntries(kwl.map(c=>[c.name,c]));
assert.deepEqual([byName['創世木下'].hp,byName['創世木下'].atk,byName['創世木下'].rarity],[100000,30000,'伝説レア']);
assert.deepEqual([byName['創世討伐兵器・零式'].hp,byName['創世討伐兵器・零式'].atk,byName['創世討伐兵器・零式'].rarity],[65000,12000,'伝説レア']);
assert.deepEqual([byName['悪の木下'].hp,byName['悪の木下'].atk,byName['悪の木下'].rarity],[500000,900,'UR']);
const hasturModule=fs.readFileSync('hastur.js','utf8');
const zeusModule=fs.readFileSync('zeus.js','utf8');
assert.match(hasturModule,/'覇風':\{hp:49725,atk:5000/);
assert.match(hasturModule,/'天使神:木下':\{hp:100000,atk:12000/);
assert.match(hasturModule,/'MiraiK':\{hp:70000,atk:3825/);
assert.match(hasturModule,/'ノヴァ木下':\{hp:70000,atk:45000/);
assert.match(hasturModule,/'アイスワイバーン':\{hp:70000,atk:9000/);
assert.match(hasturModule,/'最高神:ハスター':\{hp:80000,atk:22000/);
assert.match(zeusModule,/hp:100000, atk:40000, secondAtk:20000, thirdAtk:12000/);
assert.deepEqual([byName['覇風'].hp,byName['覇風'].atk],[49725,5000]);
assert.deepEqual([byName['天使神:木下'].hp,byName['天使神:木下'].atk],[100000,12000]);
assert.deepEqual([byName['MiraiK'].hp,byName['MiraiK'].atk],[70000,3825]);
assert.deepEqual([byName['ノヴァ木下'].hp,byName['ノヴァ木下'].atk],[70000,45000]);
assert.deepEqual([byName['アイスワイバーン'].hp,byName['アイスワイバーン'].atk],[70000,9000]);
assert.deepEqual([byName['最高神:ゼウス'].hp,byName['最高神:ゼウス'].atk,byName['最高神:ゼウス'].multiAttack],[100000,40000,[40000,20000,12000]]);
assert.deepEqual([byName['最高神:ハスター'].hp,byName['最高神:ハスター'].atk],[80000,22000]);
assert.deepEqual([byName['創世木下'].hp,byName['創世木下'].atk],[100000,18000]);
console.log('Phase 1 role-based rebalance targets passed.');
