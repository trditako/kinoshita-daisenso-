'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const html=fs.readFileSync('index.html','utf8');
const worker=fs.readFileSync('service-worker.js','utf8');
const exporter=fs.readFileSync('scripts/export-character-roster.mjs','utf8');
const cards=Array.from({length:122},(_,id)=>({id,name:'existing-'+id}));
const context={cards,charLevel:Array(122).fill(1),charMaxLevel:Array(122).fill(20),charForm:Array(122).fill(1),normalEvolved:Array(122).fill(false),ownedFlags:Array(122).fill(false),rechargeLeft:Array(122).fill(0),CURRENT_CHARACTER_COUNT:122,window:{KINOSHITA_REFRESH_CHARACTER_ROSTER_AUDIT(){this.refreshed=true;}},renderCards(){},renderFormation(){}};
vm.runInNewContext(fs.readFileSync('prism.js','utf8'),context);
assert.equal(cards.length,128);
const prismCards=cards.slice(122);
assert.equal(prismCards.length,6);
assert.deepEqual(Array.from(prismCards,c=>c.rarity),['SSR','SSR','SSR','SSR','SSR','LR']);
assert.ok(prismCards.every(c=>c.series==='PRISM木下s'&&c.limitedExchange===true&&c.limitedExchangeSeries==='PRISM木下s'));
assert.ok(prismCards.every(c=>c.skills.length===6&&c.ability.adaptation));
assert.deepEqual(Array.from(prismCards,c=>c.id),[122,123,124,125,126,127]);
assert.equal(context.charLevel.length,128);
assert.equal(context.ownedFlags.length,128);
assert.equal(context.CURRENT_CHARACTER_COUNT,128);
assert.equal(context.window.refreshed,true);
assert.match(html,/const series='PRISM木下s'/,'limited exchange shop is switched to PRISM only');
assert.match(html,/超激レア：10,000コイン／伝説レア：50,000コイン/,'shop displays the requested SSR and LR exchange prices only');
assert.match(worker,/\.\/prism\.js\?v=20261123-adaptation-series/,'service worker loads PRISM after Hastur');
assert.match(exporter,/page\.addScriptTag\(\{path:path\.join\(root,'prism\.js'\)\}\)/,'runtime roster exporter registers PRISM before export');
console.log('PRISM series and roster tests passed.');
