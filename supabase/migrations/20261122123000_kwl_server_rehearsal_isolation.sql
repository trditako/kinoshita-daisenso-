-- Isolated KWL server rehearsal storage. No foreign keys to production tournament data.
create table if not exists public.kwl_rehearsal_credentials (
  credential_key text primary key,
  secret_hash text not null check (length(secret_hash)=64),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.kwl_rehearsal_runs (
  id uuid primary key default gen_random_uuid(),
  status text not null default 'running' check (status in ('running','completed','failed')),
  engine_version text not null,
  team1_id integer not null,
  team2_id integer not null,
  team1_name text not null,
  team2_name text not null,
  team1_ai_account_id integer not null,
  team2_ai_account_id integer not null,
  team1_wins integer not null default 0 check (team1_wins between 0 and 3),
  team2_wins integer not null default 0 check (team2_wins between 0 and 3),
  games_completed integer not null default 0 check (games_completed between 0 and 5),
  winner_team_id integer,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  error text,
  created_at timestamptz not null default now()
);

create table if not exists public.kwl_rehearsal_games (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.kwl_rehearsal_runs(id) on delete cascade,
  game_number integer not null check (game_number between 1 and 5),
  status text not null default 'completed' check (status in ('completed','failed')),
  winner_team_id integer not null,
  duration_seconds numeric not null check (duration_seconds >= 0),
  engine_version text not null,
  replay jsonb not null,
  completed_at timestamptz not null default now(),
  unique (run_id, game_number)
);

create index if not exists kwl_rehearsal_runs_created_at_idx
  on public.kwl_rehearsal_runs (created_at desc);
create index if not exists kwl_rehearsal_games_run_id_idx
  on public.kwl_rehearsal_games (run_id, game_number);

alter table public.kwl_rehearsal_credentials enable row level security;
alter table public.kwl_rehearsal_runs enable row level security;
alter table public.kwl_rehearsal_games enable row level security;

revoke all on public.kwl_rehearsal_credentials from public, anon, authenticated;
revoke all on public.kwl_rehearsal_runs from public, anon, authenticated;
revoke all on public.kwl_rehearsal_games from public, anon, authenticated;
grant all on public.kwl_rehearsal_credentials to service_role;
grant all on public.kwl_rehearsal_runs to service_role;
grant all on public.kwl_rehearsal_games to service_role;
grant usage, select on sequence public.kwl_rehearsal_games_id_seq to service_role;

comment on table public.kwl_rehearsal_runs is 'Isolated server-side KWL rehearsal runs; never contributes to official tournament records or rewards.';
comment on table public.kwl_rehearsal_games is 'Server-generated replay frames for isolated KWL rehearsals.';
comment on table public.kwl_rehearsal_credentials is 'Hash-only operator credential for starting isolated KWL rehearsals.';
