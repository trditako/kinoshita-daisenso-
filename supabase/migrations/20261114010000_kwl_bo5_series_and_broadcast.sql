-- KWL BO5 series, player rotation, shared character locks and live broadcast events.
create table if not exists public.kwl_games (
  id bigint generated by default as identity primary key,
  tournament_key text not null references public.kwl_tournaments(tournament_key) on delete cascade,
  match_id bigint not null references public.kwl_matches(id) on delete cascade,
  game_number integer not null check(game_number between 1 and 5),
  status text not null default 'waiting' check(status in ('waiting','ready','live','completed','cancelled')),
  winner_team_id bigint references public.kwl_teams(id) on delete set null,
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  unique(match_id,game_number)
);
create table if not exists public.kwl_game_players (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.kwl_matches(id) on delete cascade,
  game_number integer not null check(game_number between 1 and 5),
  team_id bigint not null references public.kwl_teams(id) on delete cascade,
  player_id text not null,
  player_type text not null default 'player' check(player_type in ('player','ai')),
  player_name text not null default '',
  claimed_at timestamptz not null default now(),
  unique(match_id,game_number,team_id),
  unique(match_id,team_id,player_type,player_id),
  foreign key(match_id,game_number) references public.kwl_games(match_id,game_number) on delete cascade
);
create table if not exists public.kwl_character_locks (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.kwl_matches(id) on delete cascade,
  team_id bigint not null references public.kwl_teams(id) on delete cascade,
  character_key text not null,
  first_game_number integer not null check(first_game_number between 1 and 5),
  player_id text not null,
  player_type text not null default 'player' check(player_type in ('player','ai')),
  locked_at timestamptz not null default now(),
  unique(match_id,team_id,character_key)
);
create table if not exists public.kwl_live_events (
  id bigint generated by default as identity primary key,
  tournament_key text not null references public.kwl_tournaments(tournament_key) on delete cascade,
  match_id bigint references public.kwl_matches(id) on delete cascade,
  game_number integer check(game_number between 1 and 5),
  event_type text not null check(event_type in ('system','deployment','battle_start','battle_end','score','commentary','highlight')),
  team_id bigint references public.kwl_teams(id) on delete set null,
  player_name text not null default '',
  message text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists kwl_live_events_match_idx on public.kwl_live_events(match_id,id desc);
create index if not exists kwl_game_players_match_idx on public.kwl_game_players(match_id,game_number);
create index if not exists kwl_character_locks_match_idx on public.kwl_character_locks(match_id,team_id);

alter table public.kwl_games enable row level security;
alter table public.kwl_game_players enable row level security;
alter table public.kwl_character_locks enable row level security;
alter table public.kwl_live_events enable row level security;
drop policy if exists "KWL public read games" on public.kwl_games;
create policy "KWL public read games" on public.kwl_games for select to anon,authenticated using(true);
drop policy if exists "KWL public read game players" on public.kwl_game_players;
create policy "KWL public read game players" on public.kwl_game_players for select to anon,authenticated using(true);
drop policy if exists "KWL public read character locks" on public.kwl_character_locks;
create policy "KWL public read character locks" on public.kwl_character_locks for select to anon,authenticated using(true);
drop policy if exists "KWL public read live events" on public.kwl_live_events;
create policy "KWL public read live events" on public.kwl_live_events for select to anon,authenticated using(true);
grant select on public.kwl_games,public.kwl_game_players,public.kwl_character_locks,public.kwl_live_events to anon,authenticated;

create or replace function public.kwl_claim_game_player(
  p_match_id bigint,p_team_id bigint,p_player_id text,p_player_type text default 'player',p_player_name text default ''
) returns jsonb language plpgsql security definer set search_path=public as $$
declare m public.kwl_matches%rowtype; t public.kwl_teams%rowtype; tour public.kwl_tournaments%rowtype; g integer; member_ok boolean;
begin
  if p_player_type not in ('player','ai') or coalesce(trim(p_player_id),'')='' then raise exception '選手情報が不正です'; end if;
  select * into m from public.kwl_matches where id=p_match_id for update;
  if not found or m.status not in ('ready','live') then raise exception 'この試合は出場受付中ではありません'; end if;
  select * into tour from public.kwl_tournaments where tournament_key=m.tournament_key for update;
  if not found or now()<tour.starts_at or tour.status not in ('drawn','live') then raise exception '大会開始前、または受付停止中です'; end if;
  if p_team_id not in (m.team1_id,m.team2_id) then raise exception 'このチームは試合に参加していません'; end if;
  select * into t from public.kwl_teams where id=p_team_id;
  select exists(select 1 from jsonb_array_elements(t.roster) x
    where x.value->>'id'=p_player_id and coalesce(x.value->>'type','player')=p_player_type) into member_ok;
  if not member_ok then raise exception '登録選手ではありません'; end if;
  if exists(select 1 from public.kwl_game_players where match_id=p_match_id and team_id=p_team_id and player_type=p_player_type and player_id=p_player_id) then
    raise exception 'この選手はこのBO5シリーズですでに出場しています';
  end if;
  select x.game_number into g from public.kwl_games x
    where x.match_id=p_match_id and x.game_number<=5
      and not exists(select 1 from public.kwl_game_players gp where gp.match_id=x.match_id and gp.game_number=x.game_number and gp.team_id=p_team_id)
    order by x.game_number limit 1;
  if g is null then
    select coalesce(max(game_number),0)+1 into g from public.kwl_games where match_id=p_match_id;
    if g>5 then raise exception 'BO5の全試合枠が終了しています'; end if;
    insert into public.kwl_games(tournament_key,match_id,game_number,status)
    values(m.tournament_key,p_match_id,g,'waiting') on conflict(match_id,game_number) do nothing;
  end if;
  insert into public.kwl_game_players(match_id,game_number,team_id,player_id,player_type,player_name)
  values(p_match_id,g,p_team_id,p_player_id,p_player_type,coalesce(nullif(p_player_name,''),p_player_id));
  update public.kwl_games set status=case when exists(
    select 1 from public.kwl_game_players gp where gp.match_id=p_match_id and gp.game_number=g and gp.team_id<>p_team_id
  ) then 'ready' else 'waiting' end,
  started_at=case when exists(select 1 from public.kwl_game_players gp where gp.match_id=p_match_id and gp.game_number=g and gp.team_id<>p_team_id) then coalesce(started_at,now()) else started_at end
  where match_id=p_match_id and game_number=g;
  update public.kwl_tournaments set status='live',updated_at=now() where tournament_key=m.tournament_key and status='drawn';
  update public.kwl_matches set status='live',updated_at=now() where id=p_match_id;
  insert into public.kwl_live_events(tournament_key,match_id,game_number,event_type,team_id,player_name,message)
  values(m.tournament_key,p_match_id,g,'system',p_team_id,coalesce(nullif(p_player_name,''),p_player_id),coalesce(nullif(p_player_name,''),p_player_id)||' が第'||g||'試合に出場登録しました');
  return jsonb_build_object('success',true,'game_number',g,'team_id',p_team_id);
end $$;

create or replace function public.kwl_lock_character(
  p_match_id bigint,p_game_number integer,p_team_id bigint,p_player_id text,p_player_type text,p_character_key text
) returns jsonb language plpgsql security definer set search_path=public as $$
declare gp public.kwl_game_players%rowtype; m public.kwl_matches%rowtype; g public.kwl_games%rowtype;
begin
  if coalesce(trim(p_character_key),'')='' then raise exception 'キャラクター情報が不正です'; end if;
  select * into m from public.kwl_matches where id=p_match_id;
  if not found then raise exception '試合が見つかりません'; end if;
  select * into g from public.kwl_games where match_id=p_match_id and game_number=p_game_number for update;
  if not found or g.status not in ('ready','live') then raise exception '両チームの出場登録が完了していません'; end if;
  select * into gp from public.kwl_game_players where match_id=p_match_id and game_number=p_game_number
    and team_id=p_team_id and player_id=p_player_id and player_type=p_player_type;
  if not found then raise exception '先にこの試合への出場登録をしてください'; end if;
  if exists(select 1 from public.kwl_character_locks where match_id=p_match_id and team_id=p_team_id and character_key=p_character_key) then
    raise exception 'このキャラクターは同じ対戦カードの前の試合ですでに使用されています';
  end if;
  insert into public.kwl_character_locks(match_id,team_id,character_key,first_game_number,player_id,player_type)
  values(p_match_id,p_team_id,p_character_key,p_game_number,p_player_id,p_player_type);
  update public.kwl_games set status='live' where match_id=p_match_id and game_number=p_game_number;
  insert into public.kwl_live_events(tournament_key,match_id,game_number,event_type,team_id,player_name,message,payload)
  values(m.tournament_key,p_match_id,p_game_number,'deployment',p_team_id,gp.player_name,
    gp.player_name||' が '||p_character_key||' を出撃させました',jsonb_build_object('character',p_character_key));
  return jsonb_build_object('success',true,'character_key',p_character_key);
end $$;

create or replace function public.kwl_record_game_result(
  p_match_id bigint,p_game_number integer,p_winner_team_id bigint,p_reporter_id text
) returns jsonb language plpgsql security definer set search_path=public as $$
declare m public.kwl_matches%rowtype; g public.kwl_games%rowtype; w1 integer; w2 integer; complete_series boolean;
begin
  select * into m from public.kwl_matches where id=p_match_id for update;
  if not found then raise exception '試合結果を確定できません'; end if;
  if p_winner_team_id not in (m.team1_id,m.team2_id) then raise exception '勝者チームが不正です'; end if;
  select * into g from public.kwl_games where match_id=p_match_id and game_number=p_game_number for update;
  if not found then raise exception 'このゲームは未登録です'; end if;
  if g.status='completed' then
    if g.winner_team_id=p_winner_team_id then
      select count(*) filter(where winner_team_id=m.team1_id),count(*) filter(where winner_team_id=m.team2_id)
        into w1,w2 from public.kwl_games where match_id=p_match_id and status='completed';
      return jsonb_build_object('success',true,'already_recorded',true,'team1_wins',w1,'team2_wins',w2,
        'series_completed',(w1>=3 or w2>=3),'winner_team_id',case when w1>=3 then m.team1_id when w2>=3 then m.team2_id else null end);
    end if;
    raise exception 'このゲームの勝敗はすでに確定しています';
  end if;
  if m.status not in ('live','ready') then raise exception '試合結果を確定できません'; end if;
  if (select count(*) from public.kwl_game_players where match_id=p_match_id and game_number=p_game_number)<>2 then
    raise exception '両チームの出場選手登録が必要です';
  end if;
  update public.kwl_games set status='completed',winner_team_id=p_winner_team_id,completed_at=now()
    where match_id=p_match_id and game_number=p_game_number;
  select count(*) filter(where winner_team_id=m.team1_id),count(*) filter(where winner_team_id=m.team2_id)
    into w1,w2 from public.kwl_games where match_id=p_match_id and status='completed';
  update public.kwl_matches set team1_wins=w1,team2_wins=w2,updated_at=now() where id=p_match_id;
  complete_series:=(w1>=3 or w2>=3);
  if complete_series then
    update public.kwl_matches set winner_team_id=case when w1>=3 then m.team1_id else m.team2_id end,status='completed',updated_at=now() where id=p_match_id;
    if m.next_round_number is not null and m.next_match_number is not null then
      update public.kwl_matches set
        team1_id=case when m.next_slot=1 then case when w1>=3 then m.team1_id else m.team2_id end else team1_id end,
        team2_id=case when m.next_slot=2 then case when w1>=3 then m.team1_id else m.team2_id end else team2_id end,
        status=case when (case when m.next_slot=1 then true else team1_id is not null end)
                       and (case when m.next_slot=2 then true else team2_id is not null end) then 'ready' else status end,
        updated_at=now()
      where tournament_key=m.tournament_key and round_number=m.next_round_number and match_number=m.next_match_number;
    end if;
  end if;
  insert into public.kwl_live_events(tournament_key,match_id,game_number,event_type,team_id,message,payload)
  values(m.tournament_key,p_match_id,p_game_number,'score',p_winner_team_id,
    '第'||p_game_number||'試合終了：'||w1||' - '||w2,jsonb_build_object('team1_wins',w1,'team2_wins',w2,'series_completed',complete_series));
  return jsonb_build_object('success',true,'team1_wins',w1,'team2_wins',w2,'series_completed',complete_series,
    'winner_team_id',case when complete_series then case when w1>=3 then m.team1_id else m.team2_id end else null end);
end $$;

create or replace function public.kwl_post_commentary(
  p_match_id bigint,p_message text,p_author text default 'KWL実況'
) returns jsonb language plpgsql security definer set search_path=public as $$
declare m public.kwl_matches%rowtype; msg text;
begin
  msg=left(trim(coalesce(p_message,'')),240);
  if msg='' then raise exception '実況文が空です'; end if;
  select * into m from public.kwl_matches where id=p_match_id;
  if not found or m.status not in ('ready','live') then raise exception '実況対象の試合がありません'; end if;
  insert into public.kwl_live_events(tournament_key,match_id,event_type,player_name,message)
  values(m.tournament_key,p_match_id,'commentary',left(coalesce(p_author,'KWL実況'),32),msg);
  return jsonb_build_object('success',true);
end $$;

