-- KWL: first Kinoshita World League
create table if not exists public.kwl_tournaments (
  tournament_key text primary key,
  name text not null,
  entry_opens_at timestamptz not null,
  entry_closes_at timestamptz not null,
  bracket_draw_at timestamptz not null,
  starts_at timestamptz not null,
  max_teams integer not null default 10 check (max_teams between 2 and 10),
  status text not null default 'registration' check (status in ('registration','locked','drawn','live','completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
insert into public.kwl_tournaments
(tournament_key,name,entry_opens_at,entry_closes_at,bracket_draw_at,starts_at,max_teams)
values
('kwl-2026-01','木下ワールドリーグ 第1回大会','2026-11-17 00:00:00+09','2026-11-19 23:59:59+09','2026-11-20 00:00:00+09','2026-11-21 13:30:00+09',10)
on conflict (tournament_key) do update set
 name=excluded.name,entry_opens_at=excluded.entry_opens_at,
 entry_closes_at=excluded.entry_closes_at,bracket_draw_at=excluded.bracket_draw_at,
 starts_at=excluded.starts_at,max_teams=excluded.max_teams,updated_at=now();

create table if not exists public.kwl_teams (
 id bigint generated by default as identity primary key,
 tournament_key text not null references public.kwl_tournaments(tournament_key) on delete cascade,
 alliance_id bigint not null references public.alliances(id) on delete cascade,
 alliance_name text not null,
 leader_id text not null,
 leader_type text not null default 'player' check (leader_type in ('player','ai')),
 roster jsonb not null default '[]'::jsonb check (jsonb_typeof(roster)='array' and jsonb_array_length(roster) between 5 and 10),
 seed integer,
 created_at timestamptz not null default now(),
 unique(tournament_key,alliance_id),
 unique(tournament_key,id)
);
create unique index if not exists kwl_team_seed_unique on public.kwl_teams(tournament_key,seed) where seed is not null;

create table if not exists public.kwl_matches (
 id bigint generated by default as identity primary key,
 tournament_key text not null references public.kwl_tournaments(tournament_key) on delete cascade,
 round_number integer not null check(round_number between 1 and 4),
 match_number integer not null check(match_number between 1 and 15),
 team1_id bigint references public.kwl_teams(id) on delete set null,
 team2_id bigint references public.kwl_teams(id) on delete set null,
 winner_team_id bigint references public.kwl_teams(id) on delete set null,
 team1_wins integer not null default 0 check(team1_wins between 0 and 3),
 team2_wins integer not null default 0 check(team2_wins between 0 and 3),
 status text not null default 'pending' check(status in ('pending','ready','live','completed','bye')),
 scheduled_at timestamptz,
 live_state jsonb not null default '{}'::jsonb,
 updated_at timestamptz not null default now(),
 unique(tournament_key,round_number,match_number)
);

alter table public.kwl_tournaments enable row level security;
alter table public.kwl_teams enable row level security;
alter table public.kwl_matches enable row level security;
drop policy if exists "KWL public read tournaments" on public.kwl_tournaments;
create policy "KWL public read tournaments" on public.kwl_tournaments for select to anon,authenticated using (true);
drop policy if exists "KWL public read teams" on public.kwl_teams;
create policy "KWL public read teams" on public.kwl_teams for select to anon,authenticated using (true);
drop policy if exists "KWL public read matches" on public.kwl_matches;
create policy "KWL public read matches" on public.kwl_matches for select to anon,authenticated using (true);
grant select on public.kwl_tournaments,public.kwl_teams,public.kwl_matches to anon,authenticated;

create or replace function public.kwl_register_team(p_player_id text,p_alliance_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare a public.alliances%rowtype; t public.kwl_tournaments%rowtype; n integer; roster_json jsonb;
begin
 select * into t from public.kwl_tournaments where tournament_key='kwl-2026-01' for update;
 if not found then raise exception '大会データがありません'; end if;
 if now()<t.entry_opens_at then raise exception 'エントリー開始前です'; end if;
 if now()>t.entry_closes_at or t.status<>'registration' then raise exception 'エントリー期間外です'; end if;
 select * into a from public.alliances where id=p_alliance_id for update;
 if not found then raise exception '同盟が見つかりません'; end if;
 if a.owner_type<>'player' or a.owner_id<>p_player_id then raise exception 'エントリーできるのは同盟リーダーのみです'; end if;
 if jsonb_typeof(a.members)<>'array' then raise exception '同盟メンバー情報が不正です'; end if;
 select coalesce(jsonb_agg(x.value order by x.ordinality),'[]'::jsonb) into roster_json
 from jsonb_array_elements(a.members) with ordinality x(value,ordinality)
 where x.ordinality<=10;
 if jsonb_array_length(roster_json)<5 then raise exception '大会には5人以上の同盟メンバーが必要です'; end if;
 if exists(select 1 from public.kwl_teams where tournament_key=t.tournament_key and alliance_id=a.id) then
   raise exception 'この同盟は既にエントリー済みです';
 end if;
 select count(*) into n from public.kwl_teams where tournament_key=t.tournament_key;
 if n>=t.max_teams then raise exception '参加チーム数が上限に達しました'; end if;
 insert into public.kwl_teams(tournament_key,alliance_id,alliance_name,leader_id,leader_type,roster)
 values(t.tournament_key,a.id,a.name,a.owner_id,a.owner_type,roster_json)
 returning id into n;
 return jsonb_build_object('success',true,'team_id',n,'alliance_name',a.name,'roster',roster_json);
end $$;

revoke all on function public.kwl_register_team(text,bigint) from public;
grant execute on function public.kwl_register_team(text,bigint) to anon,authenticated;

create or replace function public.kwl_draw_bracket(p_actor_id text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare t public.kwl_tournaments%rowtype; team_ids bigint[]; slots bigint[]; i integer; m integer; r integer; a bigint; b bigint; advanced bigint; created_count integer:=0;
begin
 if p_actor_id<>'cd19b245-1a70-45de-9bb7-967f6c568425' then raise exception '大会運営者のみ実行できます'; end if;
 select * into t from public.kwl_tournaments where tournament_key='kwl-2026-01' for update;
 if not found then raise exception '大会データがありません'; end if;
 if now()<t.bracket_draw_at then raise exception '組み合わせ抽選は11月20日以降に実行できます'; end if;
 if exists(select 1 from public.kwl_matches where tournament_key=t.tournament_key) then
   return jsonb_build_object('success',true,'already_drawn',true);
 end if;
 select array_agg(id order by random()) into team_ids from public.kwl_teams where tournament_key=t.tournament_key;
 if coalesce(array_length(team_ids,1),0)<2 then raise exception '抽選には2チーム以上必要です'; end if;
 update public.kwl_teams set seed=x.rn from (
   select id,row_number() over(order by array_position(team_ids,id))::integer rn
   from public.kwl_teams where tournament_key=t.tournament_key
 ) x where kwl_teams.id=x.id;
 slots:=array_fill(null::bigint,array[16]);
 -- Standard 16-slot seed positions. Empty slots become byes and are advanced automatically.
 for i in 1..coalesce(array_length(team_ids,1),0) loop
   slots[i]:=team_ids[i];
 end loop;
 -- Pair the 16 first-round slots; compact seeded teams are randomized, then bye advancement
 -- is performed in the same bracket structure.
 for i in 1..8 loop
   a:=slots[i]; b:=slots[17-i];
   m:=i;
   if a is null or b is null then
     advanced:=coalesce(a,b);
     insert into public.kwl_matches(tournament_key,round_number,match_number,team1_id,team2_id,winner_team_id,status)
     values(t.tournament_key,1,m,a,b,advanced,'bye');
   else
     insert into public.kwl_matches(tournament_key,round_number,match_number,team1_id,team2_id,status)
     values(t.tournament_key,1,m,a,b,'ready');
   end if;
   created_count:=created_count+1;
 end loop;
 update public.kwl_tournaments set status='drawn',updated_at=now() where tournament_key=t.tournament_key;
 return jsonb_build_object('success',true,'teams',coalesce(array_length(team_ids,1),0),'first_round_matches',created_count,
   'note','第1ラウンドの組み合わせを作成しました。勝者の次ラウンド反映は運営画面で確定します。');
end $$;
revoke all on function public.kwl_draw_bracket(text) from public;
grant execute on function public.kwl_draw_bracket(text) to anon,authenticated;
